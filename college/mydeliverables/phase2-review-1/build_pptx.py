def app_props(num_slides, titles):
    def v(items):
        return "".join(f"<vt:{t}>{x}</vt:{t}>" for t, x in items)

    title_parts = v([("lpstr", t) for t in titles])
    heading_parts = (
        '<vt:variant><vt:lpstr>Theme</vt:lpstr></vt:variant>'
        '<vt:variant><vt:i4>1</vt:i4></vt:variant>'
        '<vt:variant><vt:lpstr>Slide Titles</vt:lpstr></vt:variant>'
        f'<vt:variant><vt:i4>{num_slides}</vt:i4></vt:variant>'
    )
    return f"""<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Properties xmlns="http://schemas.openxmlformats.org/officeDocument/2006/extended-properties" xmlns:vt="http://schemas.openxmlformats.org/officeDocument/2006/docPropsVTypes">
  <Application>Microsoft Office PowerPoint</Application>
  <Slides>{num_slides}</Slides>
  <HeadingPairs><vt:vector size="4" baseType="variant">{heading_parts}</vt:vector></HeadingPairs>
  <TitlesOfParts><vt:vector size="{num_slides}" baseType="lpstr">{title_parts}</vt:vector></TitlesOfParts>
</Properties>
"""


